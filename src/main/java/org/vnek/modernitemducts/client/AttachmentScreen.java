import java.util.ArrayList;
import java.util.List;
import java.util.function.BooleanSupplier;
import java.util.function.IntConsumer;
import java.util.function.IntSupplier;
import java.util.function.Supplier;

/**
 * Attachment configuration screen, drawn from two 256x256 sheets generated by
 * {@code tools/generate_assets.py}: {@code gui/attachment.png} (panel with the player inventory
 * slots) and {@code gui/widgets.png} (slots, buttons, tabs, icons; layout documented there).
 * Buttons accept left and right clicks; numeric +/- buttons step by 1, Shift+left by 16,
 * Shift+right by 4.
 */
public class AttachmentScreen extends AbstractContainerScreen<AttachmentMenu> {
    private static final ResourceLocation PANEL = ModernItemDucts.id("textures/gui/attachment.png");
    private static final ResourceLocation WIDGETS = ModernItemDucts.id("textures/gui/widgets.png");

    // icon indices in widgets.png (see ICONS in tools/generate_assets.py)
    private static final int I_ALLOW = 0, I_DENY = 1, I_DAMAGE = 2, I_NBT = 4, I_TAGS = 6, I_MOD = 8,
            I_SORT = 10, I_OVERSEND_ON = 14, I_OVERSEND_OFF = 15, I_REDSTONE = 16, I_INFO = 19, I_PLUS = 20, I_MINUS = 21;

    private final List<StateButton> stateButtons = new ArrayList<>();
    private final List<Readout> readouts = new ArrayList<>();

    public AttachmentScreen(AttachmentMenu menu, Inventory inv, Component title) {
        super(menu, inv, title);
        imageWidth = AttachmentMenu.WIDTH;
        imageHeight = AttachmentMenu.HEIGHT;
        inventoryLabelY = imageHeight - 94;
    }

    private boolean active() {
        return menu.kind != AttachmentKind.FILTER;
    }

    @Override
    protected void init() {
        super.init();
        stateButtons.clear();
        readouts.clear();

        // --- toggle row under the grid
        List<StateButton> row = new ArrayList<>();
        for (FilterSettings.Flag f : FilterSettings.Flag.values()) {
            if (!menu.tier.canChange(f)) continue;
            row.add(new StateButton(0, 0, 20, () -> flagIcon(f),
                    () -> Component.translatable("gui.modernitemducts.flag." + f.name().toLowerCase() + "." + (menu.flag(f) ? "on" : "off")),
                    btn -> send(AttachmentMenu.B_FLAG + f.ordinal()), () -> menu.flag(f)));
        }
        if (active() && menu.tier.hasSortModes()) {
            row.add(new StateButton(0, 0, 20, () -> I_SORT + menu.sortMode().ordinal(),
                    () -> Component.translatable("gui.modernitemducts.sort." + menu.sortMode().name().toLowerCase()),
                    btn -> send(btn == 0 ? AttachmentMenu.B_SORT_FWD : AttachmentMenu.B_SORT_BACK), null));
        }
        if (menu.kind == AttachmentKind.FILTER) {
            row.add(new StateButton(0, 0, 20, () -> overSend() ? I_OVERSEND_ON : I_OVERSEND_OFF,
                    () -> Component.translatable("gui.modernitemducts.oversend." + (overSend() ? "on" : "off")),
                    btn -> send(AttachmentMenu.B_OVERSEND), this::overSend));
        }
        int y = topPos + menu.gridTop + menu.tier.rows * 18 + 5;
        int total = row.size() * 26 - 6;
        int x = leftPos + (imageWidth - total) / 2;
        for (StateButton b : row) {
            b.setPosition(x, y);
            x += 26;
            addButton(b);
        }

        // --- numeric controls
        if (active()) {
            numeric(leftPos + imageWidth - 31, AttachmentMenu.B_MAX_OP, AttachmentMenu.D_MAX_OP, 1, menu.tier.maxItems,
                    "gui.modernitemducts.max_op");
        }
        if (menu.kind != AttachmentKind.SERVO && menu.tier.hasMaxStock()) {
            numeric(leftPos + 17, AttachmentMenu.B_MAX_STOCK, AttachmentMenu.D_MAX_STOCK, 0, menu.tier.maxStockLimit,
                    "gui.modernitemducts.max_stock");
        }

        // --- side tab: info and redstone mode
        addButton(new StateButton(leftPos - 22, topPos + 6, 20, () -> I_INFO,
                () -> Component.translatable("gui.modernitemducts.info." + menu.kind.name)
                        .append("\n\n").append(Component.translatable("gui.modernitemducts.info.shift")),
                btn -> {}, null));
        if (active()) {
            addButton(new StateButton(leftPos - 22, topPos + 30, 20, () -> I_REDSTONE + menu.redstoneMode().ordinal(),
                    () -> Component.translatable("gui.modernitemducts.redstone." + menu.redstoneMode().name().toLowerCase())
                            .append("\n").append(Component.translatable(menu.get(AttachmentMenu.D_POWERED) != 0
                                    ? "gui.modernitemducts.powered" : "gui.modernitemducts.unpowered")),
                    btn -> send(btn == 0 ? AttachmentMenu.B_RS_FWD : AttachmentMenu.B_RS_BACK), null));
        }
    }

    private boolean overSend() {
        return menu.get(AttachmentMenu.D_OVERSEND) != 0;
    }

    /** List mode shows allow/deny; the other flags show their feature, crossed out when ignored. */
    private int flagIcon(FilterSettings.Flag f) {
        boolean on = menu.flag(f);
        return switch (f) {
            case EXCLUDE -> on ? I_DENY : I_ALLOW;
            case IGNORE_DAMAGE -> I_DAMAGE + (on ? 1 : 0);
            case IGNORE_NBT -> I_NBT + (on ? 1 : 0);
            case IGNORE_TAGS -> I_TAGS + (on ? 1 : 0);
            case IGNORE_MOD -> I_MOD + (on ? 1 : 0);
        };
    }

    private void numeric(int x, int base, int dataIndex, int min, int max, String key) {
        StateButton plus = new StateButton(x, topPos + 19, 14, () -> I_PLUS,
                () -> Component.translatable(key), btn -> send(base + step(true, btn)), null);
        StateButton minus = new StateButton(x, topPos + 53, 14, () -> I_MINUS,
                () -> Component.translatable(key), btn -> send(base + step(false, btn)), null);
        plus.enabledWhen = () -> menu.get(dataIndex) < max;
        minus.enabledWhen = () -> menu.get(dataIndex) > min;
        addButton(plus);
        addButton(minus);
        readouts.add(new Readout(x + 7, topPos + 36, dataIndex));
    }

    /** Index into {@link AttachmentMenu#STEPS}: ±1 normally, ±16 with Shift+left, ±4 with Shift+right. */
    private static int step(boolean plus, int mouseButton) {
        int i = !Screen.hasShiftDown() ? 0 : mouseButton == 0 ? 4 : 2;
        return plus ? i : i + 1;
    }

    private record Readout(int cx, int y, int dataIndex) {}

    private void addButton(StateButton b) {
        stateButtons.add(b);
        addRenderableWidget(b);
    }

    private void send(int id) {
        Minecraft mc = Minecraft.getInstance();
        if (mc.gameMode != null) mc.gameMode.handleInventoryButtonClick(menu.containerId, id);
    }

    @Override
    protected void containerTick() {
        super.containerTick();
        for (StateButton b : stateButtons) b.refresh();
    }

    @Override
    public void render(GuiGraphics g, int mouseX, int mouseY, float partial) {
        super.render(g, mouseX, mouseY, partial); // draws the background itself since 1.20.2
        renderTooltip(g, mouseX, mouseY);
    }

    @Override
    protected void renderBg(GuiGraphics g, float partial, int mouseX, int mouseY) {
        int x = leftPos, y = topPos;
        // side tab first so the panel overlaps its open edge
        if (active()) g.blit(WIDGETS, x - 24, y + 2, 0, 60, 27, 52);
        else g.blit(WIDGETS, x - 24, y + 2, 30, 60, 27, 28);
        g.blit(PANEL, x, y, 0, 0, imageWidth, imageHeight);
        for (Slot s : menu.slots) {
            if (s instanceof AttachmentMenu.GhostSlot) g.blit(WIDGETS, x + s.x - 1, y + s.y - 1, 18, 0, 18, 18);
        }
        for (Readout r : readouts) g.blit(WIDGETS, r.cx - 12, r.y, 0, 148, 24, 12);
        // title underline in the tier colour
        g.fill(x + 8, y + 16, x + imageWidth - 8, y + 17, 0xFF000000 | menu.tier.tint);
    }

    @Override
    protected void renderLabels(GuiGraphics g, int mouseX, int mouseY) {
        super.renderLabels(g, mouseX, mouseY);
        for (Readout r : readouts) {
            int v = menu.get(r.dataIndex);
            String text = r.dataIndex == AttachmentMenu.D_MAX_STOCK && v == 0 ? "∞" : Integer.toString(v);
            g.drawString(font, text, r.cx - leftPos - font.width(text) / 2, r.y - topPos + 2, 0xFF303030, false);
        }
    }

    /** Textured button with a 12x12 icon, live tooltip and left/right click support. */
    private class StateButton extends AbstractWidget {
        private final IntSupplier icon;
        private final Supplier<Component> tooltip;
        private final IntConsumer onClick;
        private final BooleanSupplier state; // null = not a toggle
        Supplier<Boolean> enabledWhen = () -> true;
        private long pressedUntil;

        StateButton(int x, int y, int size, IntSupplier icon, Supplier<Component> tooltip, IntConsumer onClick, BooleanSupplier state) {
            super(x, y, size, size, Component.empty());
            this.icon = icon;
            this.tooltip = tooltip;
            this.onClick = onClick;
            this.state = state;
            refresh();
        }

        void refresh() {
            Component tip = tooltip.get();
            setMessage(tip);
            setTooltip(Tooltip.create(tip));
            active = enabledWhen.get();
        }

        @Override
        public boolean mouseClicked(double mx, double my, int button) {
            if (!active || !visible || (button != 0 && button != 1) || !clicked(mx, my)) return false;
            float pitch = state != null ? (state.getAsBoolean() ? 0.6f : 1.0f) : 0.8f; // switching on: higher, off: lower
            Minecraft.getInstance().getSoundManager().play(SimpleSoundInstance.forUI(SoundEvents.UI_BUTTON_CLICK, pitch));
            pressedUntil = Util.getMillis() + 120;
            onClick.accept(button);
            return true;
        }

        @Override
        protected void renderWidget(GuiGraphics g, int mouseX, int mouseY, float partial) {
            boolean hovered = isHoveredOrFocused();
            boolean pressed = Util.getMillis() < pressedUntil;
            boolean on = state != null && state.getAsBoolean();
            int sprite;
            if (!active) sprite = 3;
            else if (pressed) sprite = 2;
            else if (on) sprite = hovered ? 5 : 4;
            else sprite = hovered ? 1 : 0;
            if (width == 20) {
                g.blit(WIDGETS, getX(), getY(), sprite * 20, 20, 20, 20);
            } else {
                g.blit(WIDGETS, getX(), getY(), Math.min(sprite, 3) * 14, 40, 14, 14);
            }
            int i = icon.getAsInt();
            int u = (i % 20) * 12, v = 120 + (i / 20) * 12;
            int off = (width - 12) / 2 + (pressed ? 1 : 0);
            if (!active) {
                RenderSystem.enableBlend();
                g.setColor(1f, 1f, 1f, 0.45f);
            }
            g.blit(WIDGETS, getX() + off, getY() + off, u, v, 12, 12);
            g.setColor(1f, 1f, 1f, 1f);
            RenderSystem.disableBlend();
        }

        @Override
        protected void updateWidgetNarration(NarrationElementOutput out) {
            defaultButtonNarrationText(out);
        }
    }
}
